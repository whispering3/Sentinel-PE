import type { PeAnalysis, RuleValidationResult } from '../types'

const safeName = (value: string) =>
  value
    .replace(/[^a-zA-Z0-9_]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_|_$/g, '')
    .slice(0, 48) || 'Sample'

/**
 * Escapes arbitrary text so it is 100% valid inside a YARA double-quoted string literal.
 * Converts backslashes, quotes, control characters, and non-ASCII bytes to safe escapes.
 */
export const escapeYaraString = (raw: string, maxLen = 80): string => {
  const sliced = raw.slice(0, maxLen)
  let out = ''
  for (let i = 0; i < sliced.length; i++) {
    const code = sliced.charCodeAt(i)
    if (code === 0x5c) out += '\\\\'      // backslash
    else if (code === 0x22) out += '\\"'  // double quote
    else if (code === 0x0a) out += '\\n'  // LF
    else if (code === 0x0d) out += '\\r'  // CR
    else if (code === 0x09) out += '\\t'  // TAB
    else if (code >= 0x20 && code <= 0x7e) out += sliced[i]
    else out += `\\x${(code & 0xff).toString(16).padStart(2, '0')}`
  }
  return out
}

/**
 * Generates a deterministic RFC-4122 compliant UUID from a 64-char SHA-256 hex string
 * (or any seed string) so Sigma rules never contain an invalid nil UUID.
 */
export const deterministicUuid = (sha256Hex: string): string => {
  const clean = sha256Hex.replace(/[^a-fA-F0-9]/g, '').toLowerCase().padEnd(32, 'a').slice(0, 32)
  const p1 = clean.slice(0, 8)
  const p2 = clean.slice(8, 12)
  const p3 = `4${clean.slice(13, 16)}`
  const variantNibble = ((Number.parseInt(clean[16], 16) & 0x3) | 0x8).toString(16)
  const p4 = `${variantNibble}${clean.slice(17, 20)}`
  const p5 = clean.slice(20, 32)
  return `${p1}-${p2}-${p3}-${p4}-${p5}`
}

const escapeYamlDouble = (value: string): string =>
  value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n]+/g, ' ').trim()

// ── YARA Rule ─────────────────────────────────────────────────────────────────
export const yaraRule = (a: PeAnalysis): string => {
  const suspiciousApis = [...new Set(
    a.importedFunctions
      .filter(
        f =>
          f.name &&
          f.name.trim().length >= 4 &&
          /CryptEncrypt|BCryptEncrypt|CryptUnprotectData|VaultGetItem|CredEnumerate|MiniDumpWriteDump|VirtualAllocEx|WriteProcessMemory|CreateRemoteThread|IsDebuggerPresent|vssadmin|shadowcopy|WNetAddConnection/i.test(
            f.name,
          ),
      )
      .map(f => escapeYaraString(f.name!.trim(), 64)),
  )].slice(0, 10)

  const suspiciousStrings = [...new Set(
    [...a.strings, ...a.unicodeStrings]
      .map(s => s.trim())
      .filter(
        s =>
          s.length >= 4 &&
          /vssadmin|shadowcopy|\.onion|decrypt|ransom|bitcoin|CryptEncrypt|Login Data|Network\\Cookies|Local State|CryptUnprotectData|leveldb|tdata|lsass\.exe|sekurlsa/i.test(
            s,
          ),
      )
      .map(s => escapeYaraString(s, 80)),
  )].slice(0, 8)

  const apiLines = suspiciousApis.map((api, i) => `    $api_${i} = "${api}" ascii nocase`)
  const strLines = suspiciousStrings.map((s, i) => `    $str_${i} = "${s}" ascii wide nocase`)
  const allStringDefs = [...apiLines, ...strLines]

  const validSha256 = /^[a-f0-9]{64}$/i.test(a.sha256) ? a.sha256.toLowerCase() : ''
  const validMd5 = /^[a-f0-9]{32}$/i.test(a.md5) ? a.md5.toLowerCase() : ''
  const validImpHash = /^[a-f0-9]{32}$/i.test(a.impHash) ? a.impHash.toLowerCase() : ''

  const conditionParts: string[] = ['uint16(0) == 0x5A4D']
  if (validSha256) {
    conditionParts.push(`hash.sha256(0, filesize) == "${validSha256}"`)
  }
  if (apiLines.length > 0) {
    conditionParts.push('any of ($api_*)')
  }
  if (strLines.length > 0) {
    conditionParts.push('any of ($str_*)')
  }

  const metaLines = [
    `    description  = "Defensive rule generated by Sentinel PE"`,
    validSha256 ? `    sha256       = "${validSha256}"` : '',
    validMd5 ? `    md5          = "${validMd5}"` : '',
    validImpHash ? `    imphash      = "${validImpHash}"` : '',
    `    filename     = "${escapeYaraString(a.fileName || 'unknown.exe', 64)}"`,
    `    architecture = "${escapeYaraString(a.architecture || 'PE', 32)}"`,
    `    risk_score   = ${Math.max(0, Math.min(100, Math.round(a.riskScore)))}`,
    `    generated    = "${new Date().toISOString()}"`,
  ].filter(Boolean)

  const stringsSection =
    allStringDefs.length > 0 ? `\n  strings:\n${allStringDefs.join('\n')}\n` : ''

  return `${validSha256 ? 'import "hash"\n\n' : ''}rule Sentinel_PE_${safeName(a.fileName)}
{
  meta:
${metaLines.join('\n')}
${stringsSection}
  condition:
    ${conditionParts.join('\n    and ')}
}
`
}

// ── YARA Behavioral Rule (context-based, not hash-pinned) ─────────────────────
export const yaraRuleBehavioral = (a: PeAnalysis): string => {
  const criticals = a.findings.filter(f => f.severity === 'critical' || f.severity === 'high')
  if (criticals.length === 0) return ''

  const candidates = [...a.strings, ...a.unicodeStrings]
    .map(s => s.trim())
    .filter(s => s.length >= 4)

  const shadowStrings = candidates
    .filter(s => /vssadmin|shadowcopy|wbadmin|bcdedit.*recovery/i.test(s))
    .slice(0, 4)

  const ransomStrings = candidates
    .filter(s => /your files|decrypt|ransom|bitcoin|\.onion/i.test(s))
    .slice(0, 4)

  const stealerStrings = candidates
    .filter(
      s =>
        /Login Data|Network\\Cookies|Local State|CryptUnprotectData|leveldb|tdata|lsass\.exe|sekurlsa/i.test(
          s,
        ),
    )
    .slice(0, 4)

  const escapedUnique = [
    ...new Set(
      [...shadowStrings, ...ransomStrings, ...stealerStrings]
        .map(s => escapeYaraString(s, 80))
        .filter(s => s.length >= 4),
    ),
  ].slice(0, 10)

  if (escapedUnique.length === 0) return ''

  const strDefs = escapedUnique
    .map((s, i) => `    $behavior_${i} = "${s}" ascii wide nocase`)
    .join('\n')

  const matchExpr = escapedUnique.length >= 2 ? '2 of ($behavior_*)' : 'any of ($behavior_*)'

  return `
rule Sentinel_Behavioral_${safeName(a.fileName)}
{
  meta:
    description = "Behavioral indicators extracted by Sentinel PE"
    generated   = "${new Date().toISOString()}"
    risk_score  = ${Math.max(0, Math.min(100, Math.round(a.riskScore)))}

  strings:
${strDefs}

  condition:
    uint16(0) == 0x5A4D and ${matchExpr}
}
`
}

// ── Sigma Rule ────────────────────────────────────────────────────────────────
export const sigmaRule = (a: PeAnalysis): string => {
  const highFindings = a.findings
    .filter(f => f.severity === 'critical' || f.severity === 'high')
    .map(f => `  - ${f.category.toUpperCase()}: ${escapeYamlDouble(f.title)}`)
    .join('\n')

  const level =
    a.riskScore >= 80
      ? 'critical'
      : a.riskScore >= 50
        ? 'high'
        : a.riskScore >= 20
          ? 'medium'
          : 'low'

  const hashSelections: string[] = []
  if (/^[a-f0-9]{64}$/i.test(a.sha256)) {
    hashSelections.push(`      - 'SHA256=${a.sha256.toUpperCase()}'`)
  }
  if (/^[a-f0-9]{32}$/i.test(a.md5)) {
    hashSelections.push(`      - 'MD5=${a.md5.toUpperCase()}'`)
  }
  if (/^[a-f0-9]{40}$/i.test(a.sha1)) {
    hashSelections.push(`      - 'SHA1=${a.sha1.toUpperCase()}'`)
  }
  if (a.impHash && /^[a-f0-9]{32}$/i.test(a.impHash)) {
    hashSelections.push(`      - 'IMPHASH=${a.impHash.toUpperCase()}'`)
  }

  // Fallback if no valid hash was provided so Sigma detection block is never empty
  const detectionBlock =
    hashSelections.length > 0
      ? `  selection_hash:\n    Hashes|contains:\n${hashSelections.join('\n')}\n  condition: selection_hash`
      : `  selection_image:\n    Image|endswith: '\\${escapeYamlDouble(a.fileName || 'sample.exe').replace(/'/g, "''")}'\n  condition: selection_image`

  return `title: "Sentinel PE — ${escapeYamlDouble(a.fileName || 'Sample')}"
id: ${deterministicUuid(a.sha256 || a.md5 || a.fileName)}
status: experimental
description: |
  Defensive identification from Sentinel PE static analysis.
  Risk score: ${Math.max(0, Math.min(100, Math.round(a.riskScore)))}/100
  Key findings:
${highFindings || '  - Static triage identification'}
author: Sentinel PE
date: ${new Date().toISOString().slice(0, 10).replace(/-/g, '/')}
logsource:
  product: windows
  category: process_creation
detection:
${detectionBlock}
falsepositives:
  - Legitimate administrative or authorized execution of the analyzed binary
level: ${level}
tags:
  - attack.defense_evasion
  - attack.credential_access
  - attack.impact
`
}

// ── Built-in Rule Test Lab & Validator ────────────────────────────────────────
export const validateDetectionRules = (a: PeAnalysis): RuleValidationResult => {
  const yara = yaraRule(a) + yaraRuleBehavioral(a)
  const sigma = sigmaRule(a)
  const warnings: string[] = []

  // Validate YARA structure
  const hasRuleHeader = /rule\s+Sentinel_PE_[A-Za-z0-9_]+/.test(yara)
  const hasCondition = yara.includes('condition:') && yara.includes('uint16(0) == 0x5A4D')
  const openBraces = (yara.match(/\{/g) ?? []).length
  const closeBraces = (yara.match(/\}/g) ?? []).length
  const usesApiWildcard = yara.includes('($api_*)')
  const definesApiString = yara.includes('$api_0 =')
  const usesStrWildcard = yara.includes('($str_*)')
  const definesStrString = yara.includes('$str_0 =')

  const yaraValid =
    hasRuleHeader &&
    hasCondition &&
    openBraces > 0 &&
    openBraces === closeBraces &&
    (!usesApiWildcard || definesApiString) &&
    (!usesStrWildcard || definesStrString)

  // Validate Sigma structure
  const hasValidUuid = /id:\s+[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}/i.test(
    sigma,
  )
  const hasLogsource = sigma.includes('logsource:') && sigma.includes('product: windows')
  const hasDetection = sigma.includes('detection:') && sigma.includes('condition:')
  const noEmptyImpHash = !sigma.includes("IMPHASH=''") && !/IMPHASH=\s*['"]/.test(sigma)
  const sigmaValid = hasValidUuid && hasLogsource && hasDetection && noEmptyImpHash

  const definedStrings = yara.match(/\$(?:api|str|behavior)_\d+\s*=\s*"([^"]+)"/g) ?? []
  if (definedStrings.length === 0) {
    warnings.push(
      'Rule is hash-only (no suspicious API or behavioral strings extracted). Recompilation of the target binary will evade this rule.',
    )
  }
  if (a.confidenceScore < 50) {
    warnings.push(
      `Moderate detection confidence (${a.confidenceScore}%). Validate in a test environment to avoid false positives on administrative tools.`,
    )
  }

  return {
    yaraValid,
    sigmaValid,
    matchesCurrentSample: yaraValid && (/^[a-f0-9]{64}$/i.test(a.sha256) || definedStrings.length > 0),
    matchedStringsCount: definedStrings.length,
    warnings,
  }
}

// ── Download helpers ──────────────────────────────────────────────────────────
export const downloadText = (name: string, body: string, type = 'text/plain') => {
  const url = URL.createObjectURL(new Blob([body], { type }))
  const a = document.createElement('a')
  a.href = url
  a.download = name
  a.click()
  URL.revokeObjectURL(url)
}
